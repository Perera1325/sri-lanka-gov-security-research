#!/usr/bin/env python3
"""Generate DASHBOARD.md from the inventory and the evidence register.

Every number on the dashboard is counted from those two CSV files and from the
task list in the research plan. Run from anywhere:

    python3 scripts/build_dashboard.py

Reads and writes local files only.
"""

import re
from collections import Counter

import repo_data as rd


def render():
    _, sites = rd.read_csv(rd.INVENTORY)
    _, findings = rd.read_csv(rd.REGISTER)
    _, incidents = rd.read_csv(rd.INCIDENTS)
    inc_label = Counter(i["label"] for i in incidents)
    inc_site = Counter(i["site_id"] for i in incidents
                       if i["label"] == "CONFIRMED HISTORICAL INCIDENT")

    verification = Counter(s["domain_verification_status"] for s in sites)
    research = Counter(s["research_status"] for s in sites)
    by_status = Counter(f["finding_status"] for f in findings)
    by_severity = Counter(f["severity"] for f in findings)
    per_site = Counter(f["website"] for f in findings)

    plan_text = rd.PLAN.read_text(encoding="utf-8")
    open_plan_tasks = re.findall(r"^- \[ \] (.+)$", plan_text, flags=re.M)

    out = []
    add = out.append
    add("# Research dashboard")
    add("")
    add("Generated by `scripts/build_dashboard.py` from "
        "[`data/website-inventory.csv`](data/website-inventory.csv) and "
        "[`evidence/evidence-register.csv`](evidence/evidence-register.csv). "
        "Do not edit by hand.")
    add("")
    add("## Overview")
    add("")
    add("| Measure | Count |")
    add("| --- | --- |")
    add(f"| Websites selected | {len(sites)} |")
    add(f"| Websites verified | {verification['VERIFIED']} |")
    add(f"| Websites assessed | {research['ASSESSED'] + research['REPORTED']} |")
    add(f"| Confirmed observations | {by_status['CONFIRMED OBSERVATION']} |")
    add(f"| Suspected findings | {by_status['SUSPECTED']} |")
    add(f"| NOT TESTED items logged | {by_status['NOT TESTED']} |")
    add(f"| Informational items | {by_status['INFORMATIONAL']} |")
    add(f"| Evidence register rows | {len(findings)} |")
    add(f"| Documented historical incidents (public records) | {inc_label['CONFIRMED HISTORICAL INCIDENT']} |")
    add(f"| Unverified public reports | {inc_label['POTENTIAL RISK - NOT VERIFIED']} |")
    add("")
    add("Incident counts come from "
        "[`data/historical-incidents.csv`](data/historical-incidents.csv) and include "
        f"{inc_site[rd.SHARED_SITE_ID]} shared-infrastructure incidents. They describe "
        "past events, not the current state of any site. See the "
        "[timeline](reports/historical-incident-timeline.md) and the "
        "[national research matrix](reports/national-research-matrix.md).")
    add("")
    add("\"Verified\" means both verification checks pass and dated copies of "
        "the sources are saved. See "
        "[government-sites.md](research/government-sites.md).")
    add("")
    add("## Domain verification")
    add("")
    add("| Status | Sites |")
    add("| --- | --- |")
    for status in rd.VERIFICATION_STATUSES:
        add(f"| {status} | {verification[status]} |")
    add("")
    add("## Assessment progress")
    add("")
    add("| Status | Sites |")
    add("| --- | --- |")
    for status in rd.RESEARCH_STATUSES:
        add(f"| {status} | {research[status]} |")
    add("")
    add("## Sites")
    add("")
    add("| ID | Institution | Domain | Verification | Research | Last observed | Register rows | Past incidents | Reports |")
    add("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for s in sites:
        last = s["last_observation_date"] or "–"
        link = (f"[site](reports/individual-sites/{s['domain']}.md), "
                f"[public records](reports/individual-sites/{s['domain']}-public-records.md)")
        add(f"| {s['site_id']} | {s['institution']} | {s['domain']} | "
            f"{s['domain_verification_status']} | {s['research_status']} | "
            f"{last} | {per_site[s['domain']]} | {inc_site[s['site_id']]} | {link} |")
    add("")
    add("## Register by severity")
    add("")
    if findings:
        add("| Severity | Rows |")
        add("| --- | --- |")
        for severity in rd.SEVERITIES:
            add(f"| {severity} | {by_severity[severity]} |")
    else:
        add("The evidence register is empty. No observations have been recorded.")
    add("")
    add("## Outstanding tasks")
    add("")
    unverified = [s for s in sites if s["domain_verification_status"] != "VERIFIED"]
    unassessed = [s for s in sites if s["research_status"] in ("NOT STARTED", "IN PROGRESS")]
    suspected = [f for f in findings if f["finding_status"] == "SUSPECTED"]
    add(f"**Domain verification to complete ({len(unverified)})**")
    add("")
    for s in unverified:
        note = f" — {s['notes']}" if s["notes"] else ""
        add(f"- {s['domain']} ({s['domain_verification_status']}){note}")
    if not unverified:
        add("- None")
    add("")
    add(f"**Sites still to assess ({len(unassessed)})**")
    add("")
    for s in unassessed:
        add(f"- {s['domain']} ({s['research_status']})")
    if not unassessed:
        add("- None")
    add("")
    add(f"**Suspected findings to re-check ({len(suspected)})**")
    add("")
    for f in suspected:
        add(f"- {f['finding_id']} on {f['website']}")
    if not suspected:
        add("- None")
    add("")
    add(f"**Open items in the Phase 0 research plan ({len(open_plan_tasks)}; some concern reserve sites)**")
    add("")
    for task in open_plan_tasks:
        add(f"- {task}")
    if not open_plan_tasks:
        add("- None")
    add("")
    return "\n".join(out)


if __name__ == "__main__":
    rd.DASHBOARD.write_text(render(), encoding="utf-8")
    print(f"Wrote {rd.DASHBOARD.relative_to(rd.ROOT)}")
